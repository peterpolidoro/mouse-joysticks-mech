#!/usr/bin/env python3
"""Component pages and the station page from the registry.

    python3 atlas/pages.py          # writes docs/components/*.md, docs/components/README.md, docs/station.md

Each mechanical entry with `render: true` gets a page: its isolated render,
what it is, vendor and datasheet, where it attaches and which board
connector and cable it reaches, the schematic block page (when the PCB
repository has generated it), the firmware files and protocol verbs that
touch it, the bring-up procedure that proved it, and the open questions.
Boards, cables and external endpoints get shorter pages. Links into other
repositories are written as GitHub URLs at the tag the registry names.
"""
import pathlib, sys
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPOS = {
    "mouse-joystick-pcb": ("https://github.com/peterpolidoro/mouse-joystick-pcb", "v1.0"),
    "camera-gpio-interface-pcb": ("https://github.com/peterpolidoro/camera-gpio-interface-pcb", "main"),
    "mouse-joystick-firm": ("https://github.com/peterpolidoro/mouse-joystick-firm", "main"),
    "joystick-rig": ("https://github.com/sourishmukh/joystick-rig", "main"),
}
BOARD_DOCS = {"mouse-joystick-pcb": "docs/interface-map.md", "camera-gpio-interface-pcb": "docs/interface-map.md"}


def url(ref):
    """`<repository>/<path>` -> GitHub blob URL at the repository's tag."""
    repo, _, path = ref.partition("/")
    if repo not in REPOS:
        return ref
    base, tag = REPOS[repo]
    return f"{base}/blob/{tag}/{path}" if path else base


def link(ref):
    return f"[`{ref}`]({url(ref)})"


def firmware_links(fw):
    out = []
    for f in fw.get("files", []):
        out.append(link(f"mouse-joystick-firm/{f}"))
    return out


def page(e, by_id):
    L = [f"# {e['name']}", ""]
    if e.get("render") and e["kind"] == "mechanical":
        L += [f"![{e['name']}, the rest of the station ghosted](../../renders/part-{e['id']}.png)", ""]
    if e.get("description"):
        L += [e["description"].strip(), ""]
    rows = []
    if e.get("vendor"):
        rows.append(("Vendor", e["vendor"]))
    if e.get("part_number"):
        rows.append(("Part number", f"`{e['part_number']}`"))
    if e.get("datasheet"):
        rows.append(("Datasheet", link(e["datasheet"])))
    rows.append(("Where", {"both": "one per station", "left": "left station", "right": "right station", "rig": "one per rig"}[e["station"]]))
    if e.get("gltf_nodes"):
        rows.append(("Model nodes", ", ".join(f"`{g}`" for g in e["gltf_nodes"])))
    if e.get("repository"):
        rows.append(("Repository", f"[{e['repository']}]({url(e['repository'])}) at `{e.get('tag', 'main')}`"))
    if rows:
        L += ["| | |", "| --- | --- |"] + [f"| {k} | {v} |" for k, v in rows] + [""]
    if e.get("connects_to"):
        L += ["## Connection", "", "| Board | Connector | Cable |", "| --- | --- | --- |"]
        for c in e["connects_to"]:
            cable = c.get("cable")
            cable_s = f"[{by_id[cable]['name']}]({cable}.md)" if cable in by_id else (cable or "")
            L.append(f"| [{c['board']}]({url(c['board'] + '/' + BOARD_DOCS.get(c['board'], 'README.md'))}) | `{c['connector']}` | {cable_s} |")
        L.append("")
    if e.get("block_instance"):
        L += ["## Circuit", "",
              f"Schematic block `{e['block_instance']}` on the joystick board. The block's own page is generated in the board repository "
              f"(`docs/generated/blocks/`); until it exists, the [interface map]({url('mouse-joystick-pcb/docs/interface-map.md')}) and the "
              f"[schematic PDF]({url('mouse-joystick-pcb/docs/generated/schematic/mouse-joystick-pcb-schematic.pdf')}) cover it.", ""]
    fw = e.get("firmware")
    if fw:
        L += ["## Firmware", ""]
        if fw.get("files"):
            L += ["Files: " + ", ".join(firmware_links(fw)), ""]
        if fw.get("protocol"):
            L += ["Protocol: " + ", ".join(f"`{p}`" for p in fw["protocol"]) + f" ([protocol]({url('mouse-joystick-pcb/docs/uart-protocol.md')}))", ""]
        if fw.get("bringup"):
            L += ["Proved by: " + ", ".join(link(f"mouse-joystick-firm/{b}") for b in fw["bringup"]) + f"; measurements in the [bring-up log]({url('mouse-joystick-pcb/docs/bringup-log.md')}) by board serial.", ""]
        if fw.get("notes"):
            L += [fw["notes"], ""]
    if e.get("docs"):
        L += ["## Documents", ""] + [f"- {link(d)}" for d in e["docs"]] + [""]
    if e.get("wireviz"):
        L += [f"Harness drawing: `{e['wireviz']}` (WireViz, planned).", ""]
    if e.get("confirm"):
        L += ["## To confirm", ""] + [f"- {q}" for q in e["confirm"]] + [""]
    L += ["---", "", "Generated by `atlas/pages.py` from `atlas/components.yaml`; edit the registry, not this page."]
    return "\n".join(L) + "\n"


def main():
    reg = yaml.safe_load(open(ROOT / "atlas/components.yaml"))
    by_id = {e["id"]: e for e in reg}
    out = ROOT / "docs/components"; out.mkdir(parents=True, exist_ok=True)
    for e in reg:
        (out / f"{e['id']}.md").write_text(page(e, by_id))
    idx = ["# Components", "", "One page per thing in the rig a reader can point at, generated from the",
           "registry `atlas/components.yaml`. The [station page](../station.md) shows how the", "mechanical parts stack.", ""]
    for kind, title in (("mechanical", "Mechanical, per station"), ("board", "Boards"), ("cable", "Cables"), ("external", "External")):
        idx += [f"## {title}", ""] + [f"- [{e['name']}]({e['id']}.md)" + (f": {e['description'].strip().splitlines()[0]}" if e.get("description") else "") for e in reg if e["kind"] == kind] + [""]
    (out / "README.md").write_text("\n".join(idx) + "\n")
    station = ["# One joystick station", "",
               "The right station of the two-joystick assembly, which is the un-mirrored one;",
               "the left station is its mirror image and takes the left harness.", "",
               "![One station](../renders/station-iso.png)", "",
               "## Exploded", "",
               "Parts on the lever axis move along it away from the lever; the plates, the",
               "stage and the base move down. Order from the registry's `explode` fields.", "",
               "![Exploded, 25 %](../renders/station-exploded-25.png)", "",
               "![Exploded, 50 %](../renders/station-exploded-50.png)", "",
               "![Exploded, 100 %](../renders/station-exploded-100.png)", "",
               "## Parts", "", "| Part | Order along the lever axis | Order downward |", "| --- | ---: | ---: |"]
    for e in reg:
        ex = e.get("explode")
        if ex:
            station.append(f"| [{e['name']}](components/{e['id']}.md) | {ex['order'] if ex['axis'] == 'z' else ''} | {ex['order'] if ex['axis'] == 'y' else ''} |")
    station += ["", "The [mechanical bill of materials](bom-mechanical.md) counts every part."]
    (ROOT / "docs/station.md").write_text("\n".join(station) + "\n")
    print(f"wrote {len(reg)} component pages, docs/components/README.md and docs/station.md")


if __name__ == "__main__":
    sys.exit(main())
